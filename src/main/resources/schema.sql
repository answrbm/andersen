CREATE TABLE users(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR,
				  creation_date TIMESTAMP);
CREATE TYPE ticket_type AS ENUM ('DAY', 'WEEK', 'MONTH', 'YEAR');
CREATE TABLE tickets(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					user_id INT REFERENCES users(id) ON DELETE CASCADE,
					ticket_type TICKET_TYPE, creation_date TIMESTAMP);